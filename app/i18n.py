def tr(lang: str, key: str, **kwargs) -> str:
    """Translates a UI key into the requested language ('vi' or 'en')."""
    lang_code = lang if lang in TRANSLATIONS else DEFAULT_UI_LANGUAGE
    template = TRANSLATIONS[lang_code].get(key) or TRANSLATIONS["en"].get(key, key)
    if kwargs:
        return template.format(**kwargs)
    return template
